/* === Imports === */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { fromBinary } from "@bufbuild/protobuf";
import { FileDescriptorSetSchema } from "@bufbuild/protobuf/wkt";

/* === Constants === */

const gui = new URL("../", import.meta.url);
const descriptor = new URL("../../crates/dokime-protocol/src/descriptors.bin", gui);
const output = new URL("src-tauri/src/connection/host/operations.rs", gui);

/* === Public Functions === */

function generate() {
  const descriptors = fromBinary(FileDescriptorSetSchema, readFileSync(descriptor));
  const unary = [];
  const watches = [];
  for (const file of descriptors.file) {
    if (file.package !== "dokime.v1") continue;
    for (const service of file.service) {
      if (["Backend", "Runtime", "Remote"].includes(service.name)) continue;
      for (const method of service.method) {
        if (method.clientStreaming) continue;
        const path = `/${file.package}.${service.name}/${method.name}`;
        const request = method.inputType.replace(/^\.dokime\.v1\./, "");
        const response = method.outputType.replace(/^\.dokime\.v1\./, "");
        const operation = method.serverStreaming ? "watch" : "call";
        const row = `        "${path}" => session.${operation}::<v1::${request}, v1::${response}>("${path}", payload).await,`;
        (method.serverStreaming ? watches : unary).push(row);
      }
    }
  }
  const content = `// @generated by crates/dokime-gui/tools/host-bindings.mjs; do not edit.
use super::{Error, Session};
use dokime_sdk::v1;

pub(super) async fn call(session: &Session, path: &str, payload: &[u8]) -> Result<Vec<u8>, Error> {
    match path {
${unary.sort().join("\n")}
        _ => Err(tonic::Status::unimplemented(format!("Call {path}: This Host Contract Has No Unary Operation")).into()),
    }
}

pub(super) async fn watch(session: &Session, path: &str, payload: &[u8]) -> Result<tokio_stream::wrappers::ReceiverStream<Result<Vec<u8>, Error>>, Error> {
    match path {
${watches.sort().join("\n")}
        _ => Err(tonic::Status::unimplemented(format!("Watch {path}: This Host Contract Has No Watch Operation")).into()),
    }
}
`;
  writeFileSync(output, content);
  process.stdout.write(`Generated ${unary.length} Unary Operations and ${watches.length} Watches in ${fileURLToPath(output)}\n`);
}

/* === Entry Point === */

generate();
