/* === Imports === */

import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { create, fromBinary, toBinary, toJsonString } from "@bufbuild/protobuf";
import {
  CodeGeneratorRequestSchema,
  CodeGeneratorResponseSchema,
  FileDescriptorProtoSchema,
  FileDescriptorSetSchema,
} from "@bufbuild/protobuf/wkt";

/* === Constants === */

const gui = new URL("../", import.meta.url);
const descriptor = new URL("../../crates/dokime-protocol/src/descriptors.bin", gui);
const output = new URL("src-tauri/src/connection/host/operations.rs", gui);
const root = fileURLToPath(new URL("../../", gui));

/* === Public Functions === */

function generate() {
  const descriptors = fromBinary(FileDescriptorSetSchema, readFileSync(descriptor));
  const unary = [];
  const watches = [];
  for (const file of descriptors.file) {
    if (file.package !== "dokime.v1") continue;
    for (const service of file.service) {
      if (["Backend", "Runtime", "Remote"].includes(service.name)) continue;
      for (const method of service.method) {
        if (method.clientStreaming) continue;
        const path = `/${file.package}.${service.name}/${method.name}`;
        const request = method.inputType.replace(/^\.dokime\.v1\./, "");
        const response = method.outputType.replace(/^\.dokime\.v1\./, "");
        const operation = method.serverStreaming ? "watch" : "call";
        const row = `        "${path}" => session.${operation}::<v1::${request}, v1::${response}>("${path}", payload).await,`;
        (method.serverStreaming ? watches : unary).push(row);
      }
    }
  }
  const content = `// @generated by crates/dokime-gui/tools/host-bindings.mjs; do not edit.
use super::{Error, Session};
use dokime_protocol::v1;

pub(super) async fn call(session: &Session, path: &str, payload: &[u8]) -> Result<Vec<u8>, Error> {
    match path {
${unary.sort().join("\n")}
        _ => Err(tonic::Status::unimplemented(format!("Call {path}: This Host Contract Has No Unary Operation")).into()),
    }
}

pub(super) async fn watch(session: &Session, path: &str, payload: &[u8]) -> Result<tokio_stream::wrappers::ReceiverStream<Result<Vec<u8>, Error>>, Error> {
    match path {
${watches.sort().join("\n")}
        _ => Err(tonic::Status::unimplemented(format!("Watch {path}: This Host Contract Has No Watch Operation")).into()),
    }
}
`;
  writeFileSync(output, content);
  process.stdout.write(`Generated ${unary.length} Unary Operations and ${watches.length} Watches in ${fileURLToPath(output)}\n`);
}

function generateFrontend() {
  // Read the Product and Its Exact Pinned Library Contracts
  const productBytes = readFileSync(descriptor);
  const product = fromBinary(FileDescriptorSetSchema, productBytes);
  const metadata = spawnSync("cargo", ["metadata", "--locked", "--offline", "--format-version", "1"], {
    cwd: root,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  });
  if (metadata.status !== 0) throw new Error(metadata.stderr || "Read the Locked Host Dependency Graph");
  const library = JSON.parse(metadata.stdout).packages.find(
    (entry) => entry.name === "harmos-protocol" && entry.source?.startsWith("git+"),
  );
  if (!library) throw new Error("Resolve the Pinned Host Protocol Before Generating Desktop Messages");
  const libraryBytes = readFileSync(join(dirname(library.manifest_path), "src/descriptors.bin"));
  const librarySet = fromBinary(FileDescriptorSetSchema, libraryBytes);
  const files = new Map(product.file.map((file) => [file.name, file]));
  for (const file of librarySet.file) {
    const existing = files.get(file.name);
    if (existing) {
      const left = toJsonString(FileDescriptorProtoSchema, { ...existing, sourceCodeInfo: undefined });
      const right = toJsonString(FileDescriptorProtoSchema, { ...file, sourceCodeInfo: undefined });
      if (left !== right) throw new Error(`Regenerate Product Protocol Against Its Pinned Library: ${file.name} Differs`);
      continue;
    }
    files.set(file.name, file);
  }

  // Order Dependencies Before Invoking the Standard ES Generator
  const ordered = [];
  const added = new Set();
  const active = new Set();
  function include(name) {
    if (added.has(name)) return;
    if (active.has(name)) throw new Error(`Cyclic Host Protobuf Import: ${name}`);
    const file = files.get(name);
    if (!file) throw new Error(`Missing Host Protobuf Import: ${name}`);
    active.add(name);
    for (const dependency of file.dependency) include(dependency);
    active.delete(name);
    added.add(name);
    ordered.push(file);
  }
  for (const name of files.keys()) include(name);
  const request = create(CodeGeneratorRequestSchema, {
    protoFile: ordered,
    fileToGenerate: [...files.keys()],
    parameter: "target=ts,import_extension=js",
  });
  const generated = spawnSync(process.execPath, [fileURLToPath(new URL("node_modules/@bufbuild/protoc-gen-es/bin/protoc-gen-es", gui))], {
    input: toBinary(CodeGeneratorRequestSchema, request),
    maxBuffer: 64 * 1024 * 1024,
  });
  if (generated.status !== 0) throw new Error(generated.stderr.toString());
  const response = fromBinary(CodeGeneratorResponseSchema, generated.stdout);
  if (response.error) throw new Error(response.error);
  const destination = resolve(root, "target/generated/host");
  mkdirSync(destination, { recursive: true });
  for (const file of response.file) {
    const path = resolve(destination, file.name);
    if (!path.startsWith(`${destination}\\`) && !path.startsWith(`${destination}/`)) throw new Error("Invalid Generated Host File Path");
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, file.content.replace(/\r\n/g, "\n"));
  }
  writeFileSync(
    join(destination, "identity.ts"),
    `// Generated from the Host Protocol. Do Not Edit.\nexport const descriptorSha256 = "${createHash("sha256").update(productBytes).digest("hex")}";\n`,
  );

  // Generate the Frontend's Typed Host Boundary
  const messages = new Map();
  for (const file of files.values()) {
    for (const message of file.messageType) messages.set(`.${file.package}.${message.name}`, { file, message });
  }
  const lines = [
    "// Generated from the Host Protocol. Do Not Edit.",
    'import { unary, openStream, openClientStream, type SessionIdentity } from "@/lib/rpc/transport";',
  ];
  function schema(type, alias) {
    const entry = messages.get(type);
    if (!entry) throw new Error(`Missing Host Message: ${type}`);
    lines.push(`import { ${entry.message.name}Schema as ${alias} } from "./${entry.file.name.replace(/\.proto$/, "_pb.js")}";`);
    return entry.message;
  }
  for (const file of files.values()) {
    const productFile = file.package === "dokime.v1";
    const libraryFile = ["harmos.v1", "harmos.v1.access", "harmos.v1.status"].includes(file.package);
    if (!productFile && !libraryFile) continue;
    for (const service of file.service) {
      if (productFile && ["Backend", "Runtime", "Remote"].includes(service.name)) continue;
      if (
        libraryFile &&
        !["Status", "Listener", "Pairings", "Certificates", "Logs", "TraceEvents", "Diagnostics", "CatalogEntries"].includes(service.name)
      )
        continue;
      for (const method of service.method) {
        if (method.name.startsWith("Run")) continue;
        const prefix = productFile
          ? ""
          : file.package
              .split(".")
              .slice(2)
              .map((part) => `${part[0].toUpperCase()}${part.slice(1)}`)
              .join("");
        const fullName = `${prefix}${service.name}${method.name}`;
        const name = `${fullName[0].toLowerCase()}${fullName.slice(1)}`;
        const path = `/${file.package}.${service.name}/${method.name}`;
        const input = `${name}Input`;
        const output = `${name}Output`;
        const envelope = `${name}Envelope`;
        if (method.clientStreaming) {
          if (method.serverStreaming) continue;
          const wrapper = schema(method.inputType, envelope);
          const item = wrapper.field.find((field) => field.name === "item");
          if (!item?.typeName) throw new Error(`Upload ${path}: Missing Item Contract`);
          schema(item.typeName, input);
          schema(method.outputType, output);
          lines.push(
            `export const ${name} = (session: SessionIdentity, request: Parameters<typeof openClientStream<typeof ${input}, typeof ${output}>>[4]) => openClientStream("${path}", ${input}, ${output}, session, request, ${envelope});`,
          );
          continue;
        }
        schema(method.inputType, input);
        const wrapper = messages.get(method.outputType)?.message;
        const item = method.serverStreaming ? wrapper?.field.find((field) => field.name === "item") : undefined;
        if (item?.typeName) {
          schema(item.typeName, output);
          schema(method.outputType, envelope);
          lines.push(
            `export const ${name} = (session: SessionIdentity, request: Parameters<typeof openStream<typeof ${input}, typeof ${output}>>[4]) => openStream("${path}", ${input}, ${output}, session, request, ${envelope});`,
          );
        } else {
          schema(method.outputType, output);
          const operation = method.serverStreaming ? "openStream" : "unary";
          lines.push(
            `export const ${name} = (session: SessionIdentity, request: Parameters<typeof ${operation}<typeof ${input}, typeof ${output}>>[4]) => ${operation}("${path}", ${input}, ${output}, session, request);`,
          );
        }
      }
    }
  }
  writeFileSync(join(destination, "client.ts"), `${lines.join("\n")}\n`);
  process.stdout.write(`Generated Canonical Host Messages and Client in ${destination}\n`);
}

/* === Entry Point === */

if (process.argv.includes("--frontend")) generateFrontend();
else generate();
