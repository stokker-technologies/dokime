def generate(
    messages: Path | None,
    root: Path = ROOT,
    *,
    check: bool = False,
    export: Path | None = None,
    cargo_config: Path | None = None,
) -> None:
    prepare_harmos(root, allow_install=False, cargo_config=cargo_config)
    if export is None:
        if messages is None:
            raise ValueError("a selected contract build is required")
        export = locate(messages)
    project = tomllib.loads((root / "packages/dokime/pyproject.toml").read_text())[
        "project"
    ]
    destination = root / "packages/dokime/src/dokime"
    with tempfile.TemporaryDirectory(prefix="dokime-bindings-") as directory:
        package = Path(directory) / "package"
        subprocess.run(
            [
                "cargo",
                "harmos",
                "bindings",
                "python",
                "--export",
                str(export),
                "--output",
                str(package),
                "--distribution",
                project["name"],
                "--module",
                "dokime",
                "--package-version",
                project["version"],
                "--description",
                project["description"],
                "--license",
                project["license"],
            ],
            cwd=root,
            check=True,
        )
        source = package / "src/dokime"
        generated = {}
        for path in source.rglob("*"):
            if not path.is_file():
                continue
            relative = path.relative_to(source)
            if path.is_symlink() or (
                relative.as_posix() not in _FILES and relative.parts[0] != "_wire"
            ):
                raise ValueError(
                    f"exporter returned an unexpected SDK path: {relative}"
                )
            generated[relative] = path.read_bytes()
        for name in ("__init__.py", "__init__.pyi"):
            current = destination / name
            marker = b"# Product Client Exports\n"
            if current.is_file():
                contents = current.read_bytes()
                if marker in contents:
                    suffix = marker + contents.split(marker, 1)[1]
                    generated[Path(name)] = (
                        generated[Path(name)].rstrip() + b"\n\n" + suffix
                    )
        if not {Path(name) for name in _FILES | {"_wire/_pool.py"}}.issubset(generated):
            raise ValueError("shared exporter omitted required contract assets")
        _normalize(generated, source, root)
        for relative, data in generated.items():
            if relative.parts[0] == "_wire" and relative.suffix == ".py":
                generated[relative] = _skeleton(data.decode()).encode()
        for relative in generated:
            target = destination / relative
            ancestors = [target, *target.parents]
            if any(
                path.is_symlink()
                for path in ancestors
                if path == destination or destination in path.parents
            ):
                raise ValueError(
                    f"generated destination contains a symlink: {relative}"
                )
            if target.exists() and not target.is_file():
                raise ValueError(f"generated destination is not a file: {relative}")
        obsolete = [
            path
            for path in (destination / "_wire").rglob("*")
            if path.is_file() and path.relative_to(destination) not in generated
        ]
        if check:
            stale = [
                relative
                for relative, data in generated.items()
                if not (destination / relative).is_file()
                or (destination / relative).read_bytes() != data
            ]
            if stale or obsolete:
                raise ValueError(
                    "Python contracts are stale; regenerate from the selected Cargo build"
                )
        else:
            for relative, data in generated.items():
                target = destination / relative
                target.parent.mkdir(parents=True, exist_ok=True)
                if not target.is_file() or target.read_bytes() != data:
                    target.write_bytes(data)
            for path in obsolete:
                path.unlink()
    print("Python contracts match the selected Cargo build.")


def typescript(export: Path, *, check: bool = False) -> None:
    """Generate (Or Verify) The GUI Bindings From One Contract Export."""
    command = ["node", str(ROOT / "crates/dokime-gui/tools/bindings.mjs"), str(export)]
    if check:
        command.append("--check")
    subprocess.run(command, cwd=ROOT, check=True)


def fingerprint(root: Path = ROOT) -> str:
    """The SHA-256 of the committed contract set this tree's bindings carry."""
    digest = hashlib.sha256()
    for name in CONTRACT_SET:
        digest.update((root / "packages/dokime/src/dokime" / name).read_bytes())
    return digest.hexdigest()


def _skeleton(source: str) -> str:
    """Lay one generated wire module out in the canonical file skeleton."""
    if not source.startswith(_PROTOC, source.find("\n") + 1):
        # Exporter-Authored Modules Follow The Skeleton; Bare Packages Gain One
        source = source.replace("# Harmos\n", "# Dokime\n", 1)
        if "# === Imports === #" in source or source.removeprefix(_HEADER).strip():
            return source
        return _sections('"""Generated Wire Package"""', imports=("", ""), constants="")

    # Split Protoc Output Into Provenance, Imports And Module Body
    provenance, third_party, local, body = [], [], [], []
    docstring = '"""Generated protocol buffer code."""'
    for line in source.splitlines():
        if line.startswith("# -*- coding") or line == docstring:
            continue
        if line.startswith("#") and not body and not local and not third_party:
            provenance.append(line)
        elif line.startswith(("from dokime.", "import dokime.")):
            local.append(line)
        elif line.startswith(("from ", "import ")):
            third_party.append(line)
        elif line == "# @@protoc_insertion_point(imports)":
            local.append(line)
        else:
            body.append(line)
    content = "\n".join([*provenance, *body]).strip("\n")

    return _sections(
        docstring,
        imports=(
            "".join(f"{line}\n" for line in third_party),
            "".join(f"{line}\n" for line in local),
        ),
        constants=f"{content}\n",
    )


def _sections(docstring: str, *, imports: tuple[str, str], constants: str) -> str:
    """Render the canonical Python file skeleton around generated content."""
    third_party, local = imports
    return (
        f"{_HEADER}\n\n{docstring}\n\n"
        "# === Imports === #\n\n"
        "# Standard Library Imports\n\n"
        f"# Third Party Imports\n{third_party}\n"
        f"# Local Imports\n{local}\n"
        "# Type Checking Imports\n\n\n"
        "# === Public Exports === #\n\n"
        f"# === Constants === #\n{constants}\n"
        "# === Types === #\n\n"
        "# === Classes === #\n\n"
        "# === Public Functions === #\n\n"
        "# === Private Functions === #\n\n"
        "# === Entry Point === #\n"
    )


def _normalize(generated: dict[Path, bytes], source: Path, root: Path) -> None:
    selected = sorted(
        path
        for path in generated
        if path.as_posix() in _FILES and path.suffix in {".py", ".pyi"}
    )
    for relative in selected:
        (source / relative).write_bytes(generated[relative])
    paths = [str(source / relative) for relative in selected]
    configuration = str(root / "packages/dokime/pyproject.toml")
    subprocess.run(
        [
            sys.executable,
            "-m",
            "ruff",
            "check",
            "--select",
            "I",
            "--fix",
            "--config",
            configuration,
            *paths,
        ],
        cwd=root,
        check=True,
    )
    stubs = [str(source / path) for path in selected if path.suffix == ".pyi"]
    if stubs:
        subprocess.run(
            [
                sys.executable,
                "-m",
                "ruff",
                "check",
                "--select",
                "F401",
                "--fix",
                "--config",
                configuration,
                *stubs,
            ],
            cwd=root,
            check=True,
        )
    subprocess.run(
        [sys.executable, "-m", "ruff", "format", "--config", configuration, *paths],
        cwd=root,
        check=True,
    )
    for relative in selected:
        generated[relative] = (source / relative).read_bytes()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--language", choices=("python", "typescript"), default="python"
    )
    parser.add_argument(
        "--build-json", type=Path, default=os.environ.get("DOKIME_CONTRACT_BUILD_JSON")
    )
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--cargo-config", type=Path)
    parser.add_argument(
        "--export", type=Path, default=os.environ.get("DOKIME_CONTRACT_EXPORT")
    )
    args = parser.parse_args()
    export = None
    if args.export is not None:
        revision = (
            os.environ.get("GITHUB_SHA")
            or subprocess.check_output(
                ["git", "rev-parse", "HEAD"], cwd=ROOT, text=True
            ).strip()
        )
        export = restored(args.export, revision)
    if args.build_json is None and export is None:
        parser.error(
            "--build-json or DOKIME_CONTRACT_BUILD_JSON must select a successful Cargo build"
        )
    if args.language == "typescript":
        if export is None:
            if args.build_json is None:
                parser.error("a selected Cargo build is required")
            export = locate(args.build_json)
        typescript(export, check=args.check)
    else:
        generate(
            args.build_json,
            check=args.check,
            export=export,
            cargo_config=args.cargo_config,
        )


