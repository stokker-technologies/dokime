def generate(root: Path = ROOT, *, check: bool = False) -> None:
    proto = root / "crates/dokime-protocol/proto"
    sources = sorted((proto / "dokime").rglob("*.proto"))
    if not sources:
        raise ValueError("no protocol sources found")
    with tempfile.TemporaryDirectory(prefix="dokime-bindings-") as directory:
        temporary = Path(directory)
        subprocess.run(
            [
                "uv",
                "run",
                "--isolated",
                "--locked",
                "--only-group",
                "bindings",
                "python",
                "-m",
                "grpc_tools.protoc",
                f"-I{proto}",
                f"--python_out={temporary}",
                f"--pyi_out={temporary}",
                f"--grpc_python_out={temporary}",
                *map(str, sources),
            ],
            cwd=root,
            check=True,
        )
        generated = {
            path.relative_to(temporary): path.read_text(encoding="utf-8")
            .replace(
                "from dokime.v1 import",
                "from dokime.client._generated.dokime.v1 import",
            )
            .replace(
                "_builder.BuildTopDescriptorsAndMessages(DESCRIPTOR, 'dokime.v1.",
                "_builder.BuildTopDescriptorsAndMessages(DESCRIPTOR, 'dokime.client._generated.dokime.v1.",
            )
            for path in temporary.rglob("*")
            if path.is_file()
        }
        header = "# Generated by mise run bindings:python:generate.\n"
        for init in ["__init__.py", "dokime/__init__.py", "dokime/v1/__init__.py"]:
            generated[Path(init)] = header
        # Read the canonical generated contract without introducing another model.
        contract = (root / "crates/dokime-protocol/src/lib.rs").read_text(
            encoding="utf-8"
        )
        package = _string_constant(contract, "API_PACKAGE")
        version = _string_constant(contract, "API_VERSION")
        methods_match = re.search(
            r"pub const DISCOVERY_METHODS[^=]*=\s*&?\[(.*?)\];", contract, re.S
        )
        if methods_match is None:
            raise ValueError("canonical DISCOVERY_METHODS is missing")
        methods = re.findall(r'"([^"]+)"', methods_match[1])
        generated[Path("contract.py")] = (
            header
            + f'API_PACKAGE = "{package}"\nAPI_VERSION = "{version}"\n'
            + "DISCOVERY_METHODS = ["
            + ", ".join(f'"{m}"' for m in methods)
            + "]\n"
        )
        destination = root / DESTINATION
        obsolete = [
            p
            for p in destination.rglob("*")
            if p.is_file()
            and p.suffix in {".py", ".pyi"}
            and p.relative_to(destination) not in generated
        ]
        if check and obsolete:
            raise ValueError(f"obsolete Python binding {obsolete[0]}")
        for relative, text in generated.items():
            path = destination / relative
            if check:
                if not path.exists() or path.read_text(encoding="utf-8") != text:
                    raise ValueError(
                        f"{path} is stale; run mise run bindings:python:generate"
                    )
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
        if not check:
            for path in obsolete:
                path.unlink()
    print("Python protocol bindings are current.")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generate(check=args.check)


# === Private Functions === #


def _string_constant(source: str, name: str) -> str:
    match = re.search(r"pub const " + name + r'[^=]*=\s*"([^"]+)";', source)
    if match is None:
        raise ValueError(f"canonical {name} is missing")
    return match[1]


# === Entry Point === #

if __name__ == "__main__":
    main()
